class SiteRegistry:
    def __init__(self, sites: Optional[List[SiteDefinition]] = None):
        self._sites: Dict[str, SiteDefinition] = {
            s.name.lower(): s for s in (sites or CURATED_SITES)
        }

    def list_all(self, category: Optional[PlatformCategory] = None) -> List[SiteDefinition]:
        sites = list(self._sites.values())
        if category:
            sites = [s for s in sites if s.category == category]
        return sites

    def get(self, name: str) -> Optional[SiteDefinition]:
        return self._sites.get(name.lower())

    def count(self) -> int:
        return len(self._sites)

    def categories(self) -> List[PlatformCategory]:
        return sorted(list(set(s.category for s in self._sites.values())), key=lambda x: x.value)


# Global singleton instance
default_registry = SiteRegistry()

